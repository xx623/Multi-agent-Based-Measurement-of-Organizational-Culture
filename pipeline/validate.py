"""Validators for every agent output of the five-role prototype and the expertise extension.

Structural checks mirror the JSON Schema files generated by ``schemas.py``; the
cross-field checks below implement the rules stated in the prompts (Technical
Appendix B) that a schema cannot express:

* excerpts are verbatim in the cited sentence and at most 25 words (provenance by exact
  string matching; whether an excerpt supports a claim is the skeptic's job);
* Reader fields other than excerpts may not reproduce passage text unless the field is
  itself a verbatim, provenance-checked quote of at most 25 words (then it counts as a
  verified excerpt); otherwise passage text would cross the boundary inside the view;
* flags target existing items, MISSING_ITEM targets "none", skeptic sentences exist;
* the Reader's reply answers every flag and carries unresolved flags forward;
* claims cite view evidence, copy direction / origin / scope from the cited items and
  never widen them; episode-only claims must declare generalization;
* the critic covers every supported claim; the adjudicator covers every Judge claim,
  only narrows, lists no withheld claim in the measurement record, accounts for
  objections, keeps category summaries consistent with their claims and escalates when a
  RESOLVABLE or UNDETERMINED limitation remains.

Validators never call a model. Each returns ``(errors, warnings)``. Validation error
messages are returned to the model once as feedback, so they say what to change.
"""
from __future__ import annotations

import json
import re
from typing import Any

_QUOTE_MAP = str.maketrans({"‘": "'", "’": "'", "“": '"', "”": '"', "–": "-",
                            "—": "-", " ": " ", "…": "..."})
SCOPE_TYPE_RANK = {"unspecified": 0, "team or role": 1, "unit or function": 2, "organization-wide": 3}
SCOPE_EXTENT_RANK = {"unspecified": 0, "one": 1, "some": 2, "named": 2, "all": 3}
RELEVANCE_RANK = {"none": 0, "weak": 1, "moderate": 2, "strong": 3}
MAX_EXCERPT_WORDS = 25
NGRAM = 6
_WORD = re.compile(r"[A-Za-z0-9']+")
READER_TEXT_FIELDS = ("actor", "conduct", "timing")


class ValidationFailure(Exception):
    def __init__(self, errors: list[str]):
        super().__init__("; ".join(errors))
        self.errors = errors


# ── text helpers ───────────────────────────────────────────────────────────────

def normalize_text(text: str) -> str:
    return re.sub(r"\s+", " ", str(text).translate(_QUOTE_MAP)).strip()


def word_count(text: str) -> int:
    return len(re.findall(r"\S+", str(text)))


def parse_json_text(text: str) -> Any:
    candidate = text.strip()
    candidate = re.sub(r"^```(?:json)?\s*", "", candidate)
    candidate = re.sub(r"\s*```$", "", candidate)
    try:
        return json.loads(candidate)
    except json.JSONDecodeError:
        start, end = candidate.find("{"), candidate.rfind("}")
        if start == -1 or end <= start:
            raise ValueError("reply contains no JSON object")
        return json.loads(candidate[start:end + 1])


def sentence_index(window: dict) -> dict[str, str]:
    """sid -> normalized sentence text."""
    return {u["sid"]: normalize_text(u["text"]) for u in window["units"]}


def find_span(excerpt: str, sentence_text: str) -> tuple[int, int] | None:
    """Character span of ``excerpt`` in ``sentence_text`` after normalization, or None."""
    norm_s = normalize_text(sentence_text)
    norm_e = normalize_text(excerpt).strip(" .,;:")
    if not norm_e:
        return None
    pos = norm_s.find(norm_e)
    if pos == -1:
        pos = norm_s.lower().find(norm_e.lower())
    return None if pos == -1 else (pos, pos + len(norm_e))


def find_sentence(quote: str, window: dict) -> str | None:
    """sid of the first window sentence containing ``quote`` verbatim, or None."""
    for u in window["units"]:
        if find_span(quote, u["text"]) is not None:
            return u["sid"]
    return None


def grams(text: str, n: int = NGRAM) -> set[tuple[str, ...]]:
    toks = [t.lower() for t in _WORD.findall(normalize_text(text))]
    return {tuple(toks[i:i + n]) for i in range(0, max(0, len(toks) - n + 1))}


def passage_ngrams(window: dict) -> set[tuple[str, ...]]:
    out: set = set()
    for u in window["units"]:
        out |= grams(u["text"])
    return out


def _reader_strings(item: dict):
    for k in READER_TEXT_FIELDS:
        yield k, item.get(k)
    scope = item.get("scope") if isinstance(item.get("scope"), dict) else {}
    yield "scope.target", scope.get("target")
    for i, q in enumerate(item.get("qualifications") or []):
        yield f"qualifications[{i}]", q


def _marked_runs(text: str, passage: set) -> list[list[str]]:
    """Maximal runs of consecutive words in ``text`` that reproduce passage text (6-gram matches)."""
    toks = [t.lower() for t in _WORD.findall(normalize_text(text))]
    marked = [False] * len(toks)
    for i in range(0, max(0, len(toks) - NGRAM + 1)):
        if tuple(toks[i:i + NGRAM]) in passage:
            for j in range(i, i + NGRAM):
                marked[j] = True
    runs, i = [], 0
    while i < len(toks):
        if marked[i]:
            j = i
            while j < len(toks) and marked[j]:
                j += 1
            runs.append(toks[i:j])
            i = j
        else:
            i += 1
    return runs


def _run_grams(run: list[str]) -> set[tuple[str, ...]]:
    return {tuple(run[i:i + NGRAM]) for i in range(0, max(0, len(run) - NGRAM + 1))}


def _reader_texts(record: dict):
    for it in (record or {}).get("items", []) or []:
        if isinstance(it, dict):
            for name, val in _reader_strings(it):
                yield name, val
    for f in (record or {}).get("unresolved_flags", []) or []:
        if isinstance(f, dict):
            yield "note", f.get("note")


def verified_quote_ngrams(record: dict, window: dict) -> set[tuple[str, ...]]:
    """N-grams of passage text that may legitimately cross the boundary.

    Excerpts (at most 25 words, provenance-checked), plus verbatim fragments of at most 25
    consecutive words that the Reader quoted inside other fields; both are exact matches of
    the passage, which is the same provenance check an excerpt gets. Longer copies are
    rejected by ``passage_overlap_errors`` and therefore never reach the view.
    """
    passage = passage_ngrams(window)
    allowed: set = set()
    for it in (record or {}).get("items", []) or []:
        if isinstance(it, dict):
            allowed |= grams(it.get("excerpt", ""))
    for it in (record or {}).get("items", []) or []:
        if not isinstance(it, dict):
            continue
        for _, val in _reader_strings(it):
            if isinstance(val, str):
                for run in _marked_runs(val, passage):
                    if len(run) <= MAX_EXCERPT_WORDS:
                        allowed |= _run_grams(run)
    return allowed


def excerpt_ngrams(record: dict) -> set[tuple[str, ...]]:
    """N-grams of the verified excerpts only (the standard applied to unresolved-flag notes)."""
    allowed: set = set()
    for it in (record or {}).get("items", []) or []:
        if isinstance(it, dict):
            allowed |= grams(it.get("excerpt", ""))
    return allowed


def passage_overlap_errors(out: dict, window: dict) -> list[str]:
    """No Reader field may reproduce more than 25 consecutive passage words (the excerpt limit)."""
    passage = passage_ngrams(window)
    errors = []
    for name, val in _reader_texts(out):
        if not isinstance(val, str):
            continue
        for run in _marked_runs(val, passage):
            if len(run) > MAX_EXCERPT_WORDS:
                errors.append(f"{name} reproduces {len(run)} consecutive passage words; a field may quote at most "
                              f"{MAX_EXCERPT_WORDS} consecutive words verbatim, paraphrase the rest")
    return errors


def canon_category(name: Any, categories: list[str]) -> str | None:
    if not isinstance(name, str):
        return None
    key = re.sub(r"[\s\-_]+", " ", name.strip().lower())
    for c in categories:
        if re.sub(r"[\s\-_]+", " ", c.lower()) == key:
            return c
    hits = [c for c in categories if re.sub(r"[\s\-_]+", " ", c.lower()).startswith(key) or
            key.startswith(re.sub(r"[\s\-_]+", " ", c.lower()))]
    return hits[0] if len(hits) == 1 else None


def _nonblank(v: Any) -> bool:
    return isinstance(v, str) and bool(v.strip())


def _check_keys(obj: Any, required: set[str], where: str, errors: list[str], warnings: list[str],
                allowed_extra: set[str] | None = None) -> bool:
    if not isinstance(obj, dict):
        errors.append(f"{where}: expected an object")
        return False
    missing = required - set(obj)
    extra = set(obj) - required - (allowed_extra or set())
    if missing:
        errors.append(f"{where}: missing keys {sorted(missing)}")
    if extra:
        warnings.append(f"{where}: unexpected keys {sorted(extra)}")
    return not missing


def _enum(value: Any, allowed, where: str, errors: list[str]) -> bool:
    if value not in allowed:
        errors.append(f"{where} must be one of {list(allowed)}, got {value!r}")
        return False
    return True


def _check_scope(scope: Any, v: dict, where: str, errors: list[str], warnings: list[str]) -> bool:
    if not _check_keys(scope, {"type", "target", "extent"}, where, errors, warnings):
        return False
    ok = _enum(scope.get("type"), v["scope_type"], f"{where}.type", errors)
    ok &= _enum(scope.get("extent"), v["scope_extent"], f"{where}.extent", errors)
    if not _nonblank(scope.get("target")):
        errors.append(f"{where}.target must be a nonblank string (use 'Not stated')")
        ok = False
    return bool(ok)


def _not_wider(child: dict, parents: list[dict], where: str, errors: list[str], what: str) -> None:
    """child scope/direction/origin must stay within what the parent items/claims state."""
    if not parents:
        return
    max_type = max(SCOPE_TYPE_RANK.get(p["scope"]["type"], 0) for p in parents)
    max_ext = max(SCOPE_EXTENT_RANK.get(p["scope"]["extent"], 0) for p in parents)
    c_type = SCOPE_TYPE_RANK.get(child["scope"]["type"], 0)
    c_ext = SCOPE_EXTENT_RANK.get(child["scope"]["extent"], 0)
    if c_type > max_type:
        errors.append(f"{where}: scope.type {child['scope']['type']!r} is wider than the {what} states; copy the "
                      f"narrower scope.type")
    if c_ext > max_ext:
        errors.append(f"{where}: scope.extent {child['scope']['extent']!r} is wider than the {what} states; copy the "
                      f"narrower scope.extent")
    directions = {p["direction"] for p in parents}
    if child["direction"] not in directions | {"unclear"}:
        errors.append(f"{where}: direction {child['direction']!r} is not stated by the {what} {sorted(directions)}; "
                      f"copy the stated direction or use 'unclear'")
    origins = {p["origin"] for p in parents}
    if child["origin"] not in origins | {"unstated"}:
        errors.append(f"{where}: origin {child['origin']!r} is not stated by the {what} {sorted(origins)}; copy it or "
                      f"use 'unstated'")


# ── Reader ─────────────────────────────────────────────────────────────────────

def validate_record(out: Any, *, passage_id: str, phase: str, window: dict, vocab: dict,
                    previous: dict | None = None, critique: dict | None = None,
                    selfcheck: bool = False) -> tuple[list[str], list[str]]:
    v = vocab
    errors: list[str] = []
    warnings: list[str] = []
    req = {"passage_id", "items", "declarations", "unresolved_flags", "flag_responses", "removed_item_ids"}
    if not _check_keys(out, req, "record", errors, warnings):
        return errors, warnings
    if out.get("passage_id") != passage_id:
        errors.append("record.passage_id does not match the request")
    sents = sentence_index(window)
    raw_sents = {u["sid"]: u["text"] for u in window["units"]}
    ids: list[str] = []
    items = out["items"] if isinstance(out["items"], list) else []
    if not isinstance(out["items"], list):
        errors.append("items must be an array")
    for i, item in enumerate(items):
        where = f"items[{i}]"
        if not _check_keys(item, {"id", "actor", "conduct", "timing", "status", "content_type", "direction",
                                  "origin", "scope", "qualifications", "excerpt", "excerpt_sentence"},
                           where, errors, warnings, allowed_extra={"excerpt_span"}):
            continue
        if item["id"] in ids:
            errors.append(f"{where}: duplicate id {item['id']}")
        ids.append(item["id"])
        for k in ("actor", "conduct", "timing"):
            if not _nonblank(item.get(k)):
                errors.append(f"{where}.{k} must be nonblank")
        if item.get("status") in v["direction"] and item.get("status") not in v["status"]:
            errors.append(f"{where}.status is {item.get('status')!r}, which is a direction value; status is the "
                          f"conduct's own status: use 'ongoing' for a standing requirement or routine, 'completed' "
                          f"for a past action, 'planned' for a future one, and keep {item.get('status')!r} in direction")
        else:
            _enum(item.get("status"), v["status"], f"{where}.status", errors)
        _enum(item.get("content_type"), v["content_type"], f"{where}.content_type", errors)
        _enum(item.get("direction"), v["direction"], f"{where}.direction", errors)
        _enum(item.get("origin"), v["origin"], f"{where}.origin", errors)
        _check_scope(item.get("scope"), v, f"{where}.scope", errors, warnings)
        if not isinstance(item.get("qualifications"), list):
            errors.append(f"{where}.qualifications must be an array")
        ex, sid = item.get("excerpt"), item.get("excerpt_sentence")
        if not _nonblank(ex):
            errors.append(f"{where}.excerpt must be nonblank")
            continue
        if word_count(ex) > MAX_EXCERPT_WORDS:
            errors.append(f"{where}.excerpt has {word_count(ex)} words; the limit is {MAX_EXCERPT_WORDS} words; quote at "
                          f"most {MAX_EXCERPT_WORDS} consecutive words of the sentence")
            continue
        if sid in sents and find_span(ex, sents[sid]) is not None:
            continue
        other = find_sentence(ex, window)
        if other is not None:
            warnings.append(f"{where}.excerpt_sentence corrected from {sid!r} to {other!r} (the quote is verbatim there)")
            item["excerpt_sentence"] = other
            continue
        shown = raw_sents.get(sid, "")
        if sid not in sents:
            errors.append(f"{where}.excerpt_sentence {sid!r} is not a sentence ID of the window; use one of "
                          f"{list(sents)[:12]}")
        else:
            errors.append(f"{where}.excerpt is not verbatim: it is not an exact substring of sentence {sid}, which reads: \"{shown[:300]}\". "
                          f"Copy up to {MAX_EXCERPT_WORDS} consecutive words of it exactly, without condensing")
    ex_norm = {normalize_text(it.get("excerpt", "")).lower() for it in items if isinstance(it, dict)}
    declarations = out["declarations"] if isinstance(out["declarations"], list) else []
    if not isinstance(out["declarations"], list):
        errors.append("declarations must be an array")
    for i, d in enumerate(declarations):
        where = f"declarations[{i}]"
        if not _check_keys(d, {"id", "text", "sentence"}, where, errors, warnings):
            continue
        if d.get("sentence") not in sents:
            other = find_sentence(d.get("text", ""), window) if _nonblank(d.get("text")) else None
            if other:
                warnings.append(f"{where}.sentence corrected to {other!r}")
                d["sentence"] = other
            else:
                errors.append(f"{where}.sentence {d.get('sentence')!r} is not a sentence ID of the window")
                continue
        if not _nonblank(d.get("text")) or find_span(d["text"], sents[d["sentence"]]) is None:
            errors.append(f"{where}.text is not verbatim in sentence {d.get('sentence')}; copy the sentence exactly")
        elif normalize_text(d["text"]).lower() in ex_norm:
            warnings.append(f"{where}: the declaration text is also used as an item excerpt; a sentence is either "
                            f"reported conduct or a declaration")
    errors.extend(passage_overlap_errors(out, window))
    id_set = set(ids)
    flags = out["unresolved_flags"] if isinstance(out["unresolved_flags"], list) else []
    flag_ids: list[str] = []
    for i, f in enumerate(flags):
        where = f"unresolved_flags[{i}]"
        if not _check_keys(f, {"flag_id", "type", "target_item", "source_states", "note"}, where, errors, warnings):
            continue
        if f["flag_id"] in flag_ids:
            errors.append(f"{where}: duplicate flag_id")
        flag_ids.append(f["flag_id"])
        _enum(f.get("type"), v["flag_types"], f"{where}.type", errors)
        _enum(f.get("source_states"), v["source_states"], f"{where}.source_states", errors)
        if f.get("target_item") != "none" and f.get("target_item") not in id_set:
            errors.append(f"{where}.target_item must be an item ID or 'none'")
        if not _nonblank(f.get("note")):
            errors.append(f"{where}.note must be nonblank")
    responses = out["flag_responses"] if isinstance(out["flag_responses"], list) else []
    removed = out["removed_item_ids"] if isinstance(out["removed_item_ids"], list) else []
    if phase == "initial":
        if flags or responses or removed:
            errors.append("initial phase must have empty unresolved_flags, flag_responses and removed_item_ids")
        return errors, warnings
    prev_ids = {it["id"] for it in (previous or {}).get("items", []) if isinstance(it, dict)}
    unknown_removed = set(removed) - prev_ids
    if unknown_removed:
        errors.append(f"removed_item_ids not in the previous record: {sorted(unknown_removed)}")
    dropped = (prev_ids - set(removed)) - id_set
    if dropped:
        errors.append(f"items dropped without listing them in removed_item_ids: {sorted(dropped)}")
    expected = {f["id"] for f in (critique or {}).get("flags", []) if isinstance(f, dict)}
    answered: dict = {}
    for i, r in enumerate(responses):
        where = f"flag_responses[{i}]"
        if not _check_keys(r, {"flag_id", "action", "source_states", "reason"}, where, errors, warnings):
            continue
        _enum(r.get("action"), v["flag_response_actions"], f"{where}.action", errors)
        _enum(r.get("source_states"), v["source_states"], f"{where}.source_states", errors)
        if not _nonblank(r.get("reason")):
            errors.append(f"{where}.reason must be nonblank")
        answered[r.get("flag_id")] = r
    if critique is not None:
        missing = expected - set(answered)
        if missing:
            errors.append(f"skeptic flags without a flag_response: {sorted(missing)}; add one entry per flag")
        for fid, r in answered.items():
            if fid in expected and r.get("source_states") in ("absent", "unclear") and fid not in flag_ids:
                errors.append(f"flag {fid} has source_states {r.get('source_states')} but is not carried in "
                              f"unresolved_flags; copy it there with its type, target_item, source_states and a note")
    elif not selfcheck and responses:
        errors.append("flag_responses must be empty when neither a critique nor a self-check was supplied")
    for fid in flag_ids:
        if critique is not None and fid not in expected and not fid.startswith("SC"):
            warnings.append(f"unresolved flag {fid} was not raised by the skeptic")
    return errors, warnings


def attach_spans(record: dict, window: dict) -> None:
    """Add controller-computed excerpt_span to every item (provenance by exact match)."""
    raw = {u["sid"]: u["text"] for u in window["units"]}
    for item in record.get("items", []):
        sid = item.get("excerpt_sentence")
        if sid in raw:
            span = find_span(item.get("excerpt", ""), raw[sid])
            if span:
                item["excerpt_span"] = {"sentence": sid, "start": span[0], "end": span[1]}


# ── Evidence skeptic ───────────────────────────────────────────────────────────

def validate_critique(out: Any, *, passage_id: str, window: dict, record: dict,
                      vocab: dict) -> tuple[list[str], list[str]]:
    v = vocab
    errors: list[str] = []
    warnings: list[str] = []
    if not _check_keys(out, {"passage_id", "flags", "complete_and_supported"}, "critique", errors, warnings):
        return errors, warnings
    if out.get("passage_id") != passage_id:
        errors.append("critique.passage_id does not match the request")
    sents = sentence_index(window)
    ids = {it["id"] for it in record.get("items", []) if isinstance(it, dict)}
    seen = set()
    flags = out["flags"] if isinstance(out["flags"], list) else []
    if not isinstance(out["flags"], list):
        errors.append("flags must be an array")
    for i, f in enumerate(flags):
        where = f"flags[{i}]"
        if not _check_keys(f, {"id", "type", "target_item", "sentences", "question"}, where, errors, warnings):
            continue
        if f["id"] in seen:
            errors.append(f"{where}: duplicate id")
        seen.add(f["id"])
        if _enum(f.get("type"), v["flag_types"], f"{where}.type", errors):
            if f["type"] == "MISSING_ITEM" and f.get("target_item") != "none":
                errors.append(f"{where}: MISSING_ITEM must have target_item 'none'")
            if f["type"] != "MISSING_ITEM" and f.get("target_item") not in ids:
                errors.append(f"{where}: target_item must be an existing item ID for type {f['type']}")
        if not isinstance(f.get("sentences"), list) or not f["sentences"] or \
                any(s not in sents for s in f["sentences"]):
            errors.append(f"{where}.sentences must list sentence IDs of the window, e.g. [\"S2\"]")
        if not _nonblank(f.get("question")):
            errors.append(f"{where}.question must be nonblank")
    if not isinstance(out.get("complete_and_supported"), bool):
        errors.append("complete_and_supported must be a boolean")
    elif out["complete_and_supported"] != (len(flags) == 0):
        errors.append("complete_and_supported must be true exactly when flags is empty")
    return errors, warnings


# ── Expertise agents ───────────────────────────────────────────────────────────

def validate_assessment(out: Any, *, passage_id: str, category: str, view: dict,
                        vocab: dict) -> tuple[list[str], list[str]]:
    v = vocab
    errors: list[str] = []
    warnings: list[str] = []
    if not _check_keys(out, {"passage_id", "category", "entries"}, "assessment", errors, warnings):
        return errors, warnings
    if out.get("passage_id") != passage_id:
        errors.append("assessment.passage_id does not match the request")
    if out.get("category") != category:
        if canon_category(out.get("category"), [category]) == category:
            out["category"] = category
        else:
            errors.append(f"assessment.category must be exactly {category!r}")
    items = {it["id"]: it for it in view.get("items", [])}
    for i, e in enumerate(out["entries"] if isinstance(out["entries"], list) else []):
        where = f"entries[{i}]"
        if not _check_keys(e, {"evidence_ids", "relevance", "direction", "origin", "scope", "reasons_for",
                               "reasons_against", "unresolved"}, where, errors, warnings):
            continue
        _enum(e.get("relevance"), v["relevance"], f"{where}.relevance", errors)
        _enum(e.get("direction"), v["direction"], f"{where}.direction", errors)
        _enum(e.get("origin"), v["origin"], f"{where}.origin", errors)
        if not _check_scope(e.get("scope"), v, f"{where}.scope", errors, warnings):
            continue
        cited = [items[x] for x in e.get("evidence_ids", []) if x in items]
        unknown = [x for x in e.get("evidence_ids", []) if x not in items]
        if unknown:
            errors.append(f"{where}: unknown evidence_ids {unknown}; cite only IDs from the view")
        if e.get("relevance") != "none" and not cited:
            errors.append(f"{where}: a relevance above none needs evidence_ids from the view")
        if cited and all(it["content_type"] == "episode" for it in cited) and \
                RELEVANCE_RANK.get(e.get("relevance"), 0) > 1:
            errors.append(f"{where}: episodes alone cap relevance at weak (rule 5)")
        _not_wider(e, cited, where, errors, "cited items")
    return errors, warnings


# ── Judge ──────────────────────────────────────────────────────────────────────

def validate_judgment(out: Any, *, passage_id: str, round_no: int, view: dict, categories: list[str],
                      vocab: dict, critique: dict | None = None) -> tuple[list[str], list[str]]:
    v = vocab
    errors: list[str] = []
    warnings: list[str] = []
    req = {"passage_id", "round", "claims", "completeness_uncertain_affects", "strongest_objection",
           "objection_responses"}
    if isinstance(out, dict):
        out.setdefault("objection_responses", [])
        out.setdefault("completeness_uncertain_affects", [])
    if not _check_keys(out, req, "judgment", errors, warnings):
        return errors, warnings
    if out.get("passage_id") != passage_id:
        errors.append("judgment.passage_id does not match the request")
    if out.get("round") != round_no:
        errors.append(f"judgment.round must be {round_no}")
    items = {it["id"]: it for it in view.get("items", [])}
    claim_ids = set()
    claims = out["claims"] if isinstance(out["claims"], list) else []
    if not isinstance(out["claims"], list):
        errors.append("claims must be an array")
    for i, c in enumerate(claims):
        where = f"claims[{i}]"
        if not _check_keys(c, {"id", "category", "status", "evidence_ids", "conduct", "content_type", "direction",
                               "origin", "scope", "conduct_status", "generalized_from_event"},
                           where, errors, warnings):
            continue
        if c["id"] in claim_ids:
            errors.append(f"{where}: duplicate claim id {c['id']}")
        claim_ids.add(c["id"])
        canon = canon_category(c.get("category"), categories)
        if canon is None:
            errors.append(f"{where}.category {c.get('category')!r} is not a codebook category; use exactly one of "
                          f"{categories} (a status such as 'insufficient evidence' goes in the status field)")
        elif canon != c.get("category"):
            warnings.append(f"{where}.category normalized to {canon!r}")
            c["category"] = canon
        _enum(c.get("status"), v["claim_status"], f"{where}.status", errors)
        _enum(c.get("content_type"), v["content_type"], f"{where}.content_type", errors)
        _enum(c.get("direction"), v["direction"], f"{where}.direction", errors)
        _enum(c.get("origin"), v["origin"], f"{where}.origin", errors)
        _enum(c.get("conduct_status"), v["status"], f"{where}.conduct_status", errors)
        if not _nonblank(c.get("conduct")):
            errors.append(f"{where}.conduct must be nonblank")
        if not isinstance(c.get("generalized_from_event"), bool):
            errors.append(f"{where}.generalized_from_event must be a boolean")
        if not _check_scope(c.get("scope"), v, f"{where}.scope", errors, warnings):
            continue
        eids = c.get("evidence_ids") if isinstance(c.get("evidence_ids"), list) else []
        unknown = [x for x in eids if x not in items]
        if unknown:
            errors.append(f"{where}: evidence_ids not in the view: {unknown}; cite only IDs from the view (rule 1)")
        cited = [items[x] for x in eids if x in items]
        if c.get("status") != "insufficient evidence" and not cited:
            errors.append(f"{where}: a supported or partially supported claim needs evidence_ids from the view")
        if cited and all(it["content_type"] == "episode" for it in cited) and \
                c.get("status") != "insufficient evidence" and c.get("generalized_from_event") is not True:
            errors.append(f"{where}: all cited items are episodes; set generalized_from_event true or lower the "
                          f"status to 'insufficient evidence' (rule 3)")
        if cited and c.get("conduct_status") == "ongoing" and all(it["status"] == "planned" for it in cited):
            errors.append(f"{where}: planned conduct cannot support an ongoing claim (rule 2)")
        _not_wider(c, cited, where, errors, "cited view items")
    affects = out.get("completeness_uncertain_affects")
    if not isinstance(affects, list) or any(a not in claim_ids for a in affects):
        errors.append("completeness_uncertain_affects must list existing claim ids (or be empty)")
    elif view.get("completeness_uncertain") and not affects and claims:
        warnings.append("completeness_uncertain is true but no claim is listed as affected (rule 6)")
    if not _nonblank(out.get("strongest_objection")):
        errors.append("strongest_objection must be nonblank (rule 7)")
    responses = out["objection_responses"] if isinstance(out["objection_responses"], list) else []
    if round_no == 1 and responses:
        errors.append("objection_responses must be empty in round 1")
    expected = {o["id"] for o in (critique or {}).get("objections", []) if isinstance(o, dict)}
    answered = set()
    for i, r in enumerate(responses):
        where = f"objection_responses[{i}]"
        if not _check_keys(r, {"objection_id", "action", "evidence_ids", "reason"}, where, errors, warnings):
            continue
        _enum(r.get("action"), v["objection_response_actions"], f"{where}.action", errors)
        if not _nonblank(r.get("reason")):
            errors.append(f"{where}.reason must be nonblank")
        unknown = [x for x in (r.get("evidence_ids") or []) if x not in items]
        if unknown:
            errors.append(f"{where}: evidence_ids not in the view: {unknown}")
        answered.add(r.get("objection_id"))
    if critique is not None:
        missing = expected - answered
        if missing:
            errors.append(f"critic objections without a response: {sorted(missing)}; add one objection_responses "
                          f"entry per objection id")
    elif round_no == 2 and responses:
        errors.append("objection_responses must be empty when no critic challenge was supplied")
    return errors, warnings


# ── Interpretive critic ────────────────────────────────────────────────────────

def validate_interpretive_critique(out: Any, *, passage_id: str, round_no: int, judgment: dict, view: dict,
                                   vocab: dict, prior: dict | None = None,
                                   prior_judgment: dict | None = None) -> tuple[list[str], list[str]]:
    v = vocab
    errors: list[str] = []
    warnings: list[str] = []
    req = {"passage_id", "round", "objections", "accepted_claims", "resolved_objection_ids"}
    if not _check_keys(out, req, "interpretive_critique", errors, warnings):
        return errors, warnings
    if out.get("passage_id") != passage_id:
        errors.append("interpretive_critique.passage_id does not match the request")
    if out.get("round") != round_no:
        errors.append(f"interpretive_critique.round must be {round_no}")
    claims = {c["id"]: c for c in judgment.get("claims", []) if isinstance(c, dict)}
    earlier = {c["id"]: c for c in (prior_judgment or {}).get("claims", []) if isinstance(c, dict)}
    items = {it["id"] for it in view.get("items", [])}
    seen = set()
    covered = set()
    objections = out["objections"] if isinstance(out["objections"], list) else []
    for i, o in enumerate(objections):
        where = f"objections[{i}]"
        if not _check_keys(o, {"id", "claim_ref", "criterion", "evidence_ids", "reason", "narrowest_claim"},
                           where, errors, warnings):
            continue
        if o["id"] in seen:
            errors.append(f"{where}: duplicate objection id {o['id']}")
        seen.add(o["id"])
        ref = o.get("claim_ref")
        if ref not in claims:
            if ref in earlier:
                warnings.append(f"{where}.claim_ref {ref!r} refers to a claim the Judge withdrew in round 2")
            else:
                errors.append(f"{where}.claim_ref {ref!r} is not a Judge claim id; use one of "
                              f"{sorted(claims) or sorted(earlier)}")
        covered.add(ref)
        _enum(o.get("criterion"), sorted(v["critic_criteria"]), f"{where}.criterion", errors)
        unknown = [x for x in (o.get("evidence_ids") or []) if x not in items]
        if unknown:
            errors.append(f"{where}: evidence_ids not in the view: {unknown}")
        for k in ("reason", "narrowest_claim"):
            if not _nonblank(o.get(k)):
                errors.append(f"{where}.{k} must be nonblank")
    for i, a in enumerate(out["accepted_claims"] if isinstance(out["accepted_claims"], list) else []):
        where = f"accepted_claims[{i}]"
        if not _check_keys(a, {"claim_ref", "reason"}, where, errors, warnings):
            continue
        if a.get("claim_ref") not in claims and a.get("claim_ref") not in earlier:
            errors.append(f"{where}.claim_ref {a.get('claim_ref')!r} is not a Judge claim id")
        covered.add(a.get("claim_ref"))
        if not _nonblank(a.get("reason")):
            errors.append(f"{where}.reason must be nonblank")
    substantive = {cid for cid, c in claims.items() if c.get("status") != "insufficient evidence"}
    uncovered = substantive - covered
    if uncovered:
        errors.append(f"supported or partially supported claims neither objected to nor accepted: {sorted(uncovered)}; "
                      f"add an objection or an accepted_claims entry for each")
    resolved = out.get("resolved_objection_ids")
    if not isinstance(resolved, list):
        errors.append("resolved_objection_ids must be an array")
    elif round_no == 1 and resolved:
        errors.append("resolved_objection_ids must be empty in round 1")
    elif round_no == 2:
        prior_ids = {o["id"] for o in (prior or {}).get("objections", []) if isinstance(o, dict)}
        unknown = set(resolved) - prior_ids
        if unknown:
            errors.append(f"resolved_objection_ids not raised in round 1: {sorted(unknown)}")
        overlap = set(resolved) & seen
        if overlap:
            errors.append(f"objections listed as both resolved and continuing: {sorted(overlap)}; an objection is "
                          f"either in resolved_objection_ids or kept in objections, not both")
    return errors, warnings


# ── Adjudicator ────────────────────────────────────────────────────────────────

def validate_adjudication(out: Any, *, passage_id: str, view: dict, judgment2: dict, critique1: dict,
                          critique2: dict, categories: list[str], vocab: dict) -> tuple[list[str], list[str]]:
    v = vocab
    errors: list[str] = []
    warnings: list[str] = []
    if not _check_keys(out, {"passage_id", "measurement", "process"}, "adjudication", errors, warnings):
        return errors, warnings
    if out.get("passage_id") != passage_id:
        errors.append("adjudication.passage_id does not match the request")
    m, p = out.get("measurement"), out.get("process")
    if not _check_keys(m, {"passage_id", "categories"}, "measurement", errors, warnings) or \
            not _check_keys(p, {"passage_id", "actions", "unresolved_objections", "escalate_to_human", "output_state"},
                            "process", errors, warnings, allowed_extra={"abstention_reason"}):
        return errors, warnings
    items = {it["id"]: it for it in view.get("items", [])}
    jclaims = {c["id"]: c for c in judgment2.get("claims", []) if isinstance(c, dict)}
    cats = m.get("categories")
    if not isinstance(cats, dict):
        errors.append("measurement.categories must be an object")
        return errors, warnings
    for key in list(cats):
        canon = canon_category(key, categories)
        if canon and canon != key and canon not in cats:
            cats[canon] = cats.pop(key)
            warnings.append(f"measurement.categories key {key!r} normalized to {canon!r}")
    missing = set(categories) - set(cats)
    extra = set(cats) - set(categories)
    if missing:
        errors.append(f"measurement.categories missing {sorted(missing)}; every category needs an entry (relevance "
                      f"none with empty claims when nothing is retained)")
    if extra:
        errors.append(f"measurement.categories has unknown categories {sorted(extra)}")
    limitation_kinds = []
    for name in categories:
        cat = cats.get(name)
        where = f"categories[{name!r}]"
        if not _check_keys(cat, {"relevance", "direction", "claims"}, where, errors, warnings):
            continue
        _enum(cat.get("relevance"), v["relevance"], f"{where}.relevance", errors)
        _enum(cat.get("direction"), v["category_direction"], f"{where}.direction", errors)
        claims = cat["claims"] if isinstance(cat["claims"], list) else []
        strengths = []
        for j, c in enumerate(claims):
            cw = f"{where}.claims[{j}]"
            if not _check_keys(c, {"claim_ref", "relevance", "conduct", "content_type", "direction", "origin",
                                   "scope", "conduct_status", "evidence_for", "evidence_against", "limitations"},
                               cw, errors, warnings):
                continue
            _enum(c.get("relevance"), v["relevance"], f"{cw}.relevance", errors)
            if c.get("relevance") == "none":
                errors.append(f"{cw}: a claim with relevance none must not be listed in measurement; remove it from "
                              f"claims and record it only in process.actions as {{claim_ref: {c.get('claim_ref')!r}, "
                              f"action: withhold}}")
            _enum(c.get("content_type"), v["content_type"], f"{cw}.content_type", errors)
            _enum(c.get("direction"), v["direction"], f"{cw}.direction", errors)
            _enum(c.get("origin"), v["origin"], f"{cw}.origin", errors)
            _enum(c.get("conduct_status"), v["status"], f"{cw}.conduct_status", errors)
            if not _check_scope(c.get("scope"), v, f"{cw}.scope", errors, warnings):
                continue
            unknown = [x for x in (c.get("evidence_for") or []) + (c.get("evidence_against") or []) if x not in items]
            if unknown:
                errors.append(f"{cw}: evidence ids not in the view: {unknown}")
            if c.get("relevance") != "none" and not c.get("evidence_for"):
                errors.append(f"{cw}: a claim with relevance above none needs evidence_for")
            parent = jclaims.get(c.get("claim_ref"))
            if parent is None:
                errors.append(f"{cw}.claim_ref {c.get('claim_ref')!r} is not a round-2 Judge claim; only claims the "
                              f"Judge kept in round 2 can be accepted or narrowed")
            else:
                if parent.get("category") != name:
                    errors.append(f"{cw}: claim {c['claim_ref']} belongs to category {parent.get('category')!r}")
                _not_wider(c, [parent], cw, errors, "Judge's claim")
            for k, lim in enumerate(c.get("limitations") or []):
                lw = f"{cw}.limitations[{k}]"
                if _check_keys(lim, {"text", "kind"}, lw, errors, warnings):
                    _enum(lim.get("kind"), v["limitation_kinds"], f"{lw}.kind", errors)
                    limitation_kinds.append(lim.get("kind"))
            if c.get("relevance") != "none":
                strengths.append((RELEVANCE_RANK.get(c.get("relevance"), 0), c.get("direction")))
        max_rel = max((s[0] for s in strengths), default=0)
        if RELEVANCE_RANK.get(cat.get("relevance"), -1) != max_rel:
            errors.append(f"{where}.relevance must equal the maximum claim relevance "
                          f"({[k for k, r in RELEVANCE_RANK.items() if r == max_rel][0]})")
        if not strengths:
            if cat.get("direction") != "none":
                errors.append(f"{where}.direction must be 'none' when the category has no retained claim")
        else:
            top = {d for r, d in strengths if r == max_rel}
            expected_dir = top.pop() if len(top) == 1 else "mixed"
            if cat.get("direction") != expected_dir:
                errors.append(f"{where}.direction must be {expected_dir!r} (the strongest claim's direction, or "
                              f"'mixed' when equally strong claims disagree)")
    actions = p["actions"] if isinstance(p["actions"], list) else []
    acted = {}
    for i, a in enumerate(actions):
        where = f"process.actions[{i}]"
        if not _check_keys(a, {"claim_ref", "action"}, where, errors, warnings):
            continue
        if a.get("claim_ref") not in jclaims:
            errors.append(f"{where}.claim_ref {a.get('claim_ref')!r} is not a round-2 Judge claim; actions list "
                          f"exactly the Judge's round-2 claims {sorted(jclaims)}")
        _enum(a.get("action"), v["adjudication_actions"], f"{where}.action", errors)
        acted[a.get("claim_ref")] = a.get("action")
    unacted = set(jclaims) - set(acted)
    if unacted:
        errors.append(f"process.actions must cover every round-2 Judge claim; missing {sorted(unacted)}")
    kept = {c["claim_ref"] for name in categories for c in (cats.get(name) or {}).get("claims", [])
            if isinstance(c, dict)}
    for ref, action in acted.items():
        if action == "withhold" and ref in kept:
            errors.append(f"claim {ref} has action withhold in process but is still listed in measurement; remove "
                          f"it from measurement.categories[...].claims (withheld claims appear only in process.actions)")
        if action in ("accept", "narrow") and ref not in kept and ref in jclaims and \
                jclaims[ref].get("status") != "insufficient evidence":
            errors.append(f"claim {ref} is {action}ed in process but absent from measurement; list it under its "
                          f"category with relevance weak, moderate or strong")
    all_obj = {o["id"] for src in (critique1, critique2) for o in src.get("objections", []) if isinstance(o, dict)}
    unresolved = p["unresolved_objections"] if isinstance(p["unresolved_objections"], list) else []
    unknown = set(unresolved) - all_obj
    if unknown:
        errors.append(f"process.unresolved_objections not raised by either critic round: {sorted(unknown)}")
    if not isinstance(p.get("escalate_to_human"), bool):
        errors.append("process.escalate_to_human must be a boolean")
    else:
        must = any(k in ("RESOLVABLE", "UNDETERMINED") for k in limitation_kinds) or \
            bool(view.get("completeness_uncertain"))
        if must and not p["escalate_to_human"]:
            errors.append("escalate_to_human must be true: a RESOLVABLE or UNDETERMINED limitation remains or "
                          "completeness_uncertain is true (rule 4)")
    _enum(p.get("output_state"), ["valid", "abstained"], "process.output_state", errors)
    if p.get("output_state") == "abstained" and kept:
        errors.append(f"output_state is abstained but measurement still lists claims {sorted(kept)}; an abstention "
                      f"decides no category: withhold those claims (relevance none, empty claims) or set output_state "
                      f"to valid")
    if p.get("output_state") == "abstained" and not _nonblank(p.get("abstention_reason")):
        errors.append("abstention_reason must be given when output_state is abstained")
    return errors, warnings
